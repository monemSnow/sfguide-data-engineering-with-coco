-- Option 1: Create a fresh new PAT with a role restriction
ALTER USER MONEMT0926 ADD PROGRAMMATIC ACCESS TOKEN DEMO_PAT
  ROLE_RESTRICTION = 'DEMO_ROLE'
  DAYS_TO_EXPIRY = 15;

-- Bypass network enforcement from Snowflake for 120 min
ALTER USER MONEMT0926 MODIFY PROGRAMMATIC ACCESS TOKEN DEMO_PAT
  SET MINS_TO_BYPASS_NETWORK_POLICY_REQUIREMENT = 120;



-- Advanced permanent network setup

CREATE NETWORK RULE DEMO_DB.TPCH_TRANSFORMED.MONEM_ALLOWED_IPS
  MODE = INGRESS
  TYPE = IPV4
  VALUE_LIST = ('XXX.XXX.XXX.XXX', 'XXX.XXX.XXX.XXX/29')
  COMMENT = 'Allowed IP ranges for MONEMT0926 dbt/PAT connections';

CREATE NETWORK POLICY MONEM_NETWORK_POLICY
  ALLOWED_NETWORK_RULE_LIST = (DEMO_DB.TPCH_TRANSFORMED.MONEM_ALLOWED_IPS)
  COMMENT = 'Network policy for MONEM allowing dbt PAT connections';

ALTER USER MONEMT0926 SET NETWORK_POLICY = MONEM_NETWORK_POLICY;









-- Option 2: Set a role restriction on an existing PAT
--   ROLE_RESTRICTION is immutable after creation, so you must
--   remove the token and re-create it with the desired role.
ALTER USER MONEMT0926 REMOVE PROGRAMMATIC ACCESS TOKEN DEMO_PAT;
ALTER USER MONEMT0926 ADD PROGRAMMATIC ACCESS TOKEN DEMO_PAT
  ROLE_RESTRICTION = 'DEMO_ROLE'
  DAYS_TO_EXPIRY = 15;